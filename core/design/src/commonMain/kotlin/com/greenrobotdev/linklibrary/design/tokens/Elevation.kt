package com.greenrobotdev.linklibrary.design.tokens

import androidx.compose.ui.unit.dp

/**
 * Material Design 3 Elevation Tokens
 * Tonal elevation system for depth hierarchy
 */
object ElevationTokens {
    // No elevation
    val None = 0.dp

    // Level 1 - Cards, raised buttons
    val Level1 = 1.dp

    // Level 2 - Dropdown menus, navigation bar
    val Level2 = 3.dp

    // Level 3 - FAB, dialogs, search
    val Level3 = 6.dp

    // Level 4 - Bottom sheets, side sheets
    val Level4 = 8.dp

    // Level 5 - Modal bottom sheets, large dialogs
    val Level5 = 12.dp
}
