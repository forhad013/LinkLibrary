package com.greenrobotdev.linklibrary.design.tokens

import androidx.compose.ui.unit.dp

/**
 * Material Design 3 Spacing Tokens
 * 8dp grid-based spacing system for consistent layouts
 */
object SpacingTokens {
    // Base spacing unit
    val None = 0.dp
    val Base = 8.dp

    // Micro spacing
    val Micro = 2.dp
    val Tiny = 4.dp

    // Small spacing
    val ExtraSmall = 8.dp
    val Small = 12.dp

    // Medium spacing
    val Medium = 16.dp
    val MediumLarge = 20.dp

    // Large spacing
    val Large = 24.dp
    val ExtraLarge = 32.dp

    // Extra large spacing
    val XXLarge = 40.dp
    val XXXLarge = 48.dp

    // Massive spacing
    val Massive = 64.dp
}
